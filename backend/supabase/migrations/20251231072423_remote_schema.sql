CREATE OR REPLACE FUNCTION "public"."status_close_closetime"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
begin
    if NEW.status = 'Close' and OLD.status is distinct from NEW.status
    then NEW.CloseTime := NOW();
    
    end if;
  return new; -- trả về bản ghi sau khi chỉnh sửa
end;
$$;


ALTER FUNCTION "public"."status_close_closetime"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."status_open_closetime"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
begin
    if NEW.status = 'Open' and OLD.status is distinct from NEW.status
    then NEW.CloseTime := NULL;
    end if;
  return new; --trả về bản ghi sau chỉnh sửa
end;
$$;


