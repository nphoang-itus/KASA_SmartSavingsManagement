CREATE OR REPLACE FUNCTION "public"."create_useraccount_after_employee"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
DECLARE
    initials TEXT := '';
    word TEXT;
BEGIN
    -- Tách fullName thành các từ và lấy chữ cái đầu
    FOR word IN SELECT unnest(string_to_array(NEW.fullName, ' ')) LOOP
        initials := initials || lower(left(word, 1));
    END LOOP;

    -- Chèn vào UserAccount với password = initials + employeeID
    INSERT INTO UserAccount (userID, password, AccountStatus)
    VALUES (NEW.employeeID, initials || NEW.employeeID::text, 'Unsubmitted');

    RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."create_useraccount_after_employee"() OWNER TO "postgres";


