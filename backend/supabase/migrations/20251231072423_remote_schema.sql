CREATE OR REPLACE FUNCTION "public"."gen_employee_id_v2"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
DECLARE
    next_suffix int;
BEGIN
    -- Tăng số thứ tự
    UPDATE EmpCounter
    SET lastNumber = lastNumber + 1
    WHERE branchID = NEW.branchID AND roleID = NEW.roleID
    RETURNING lastNumber INTO next_suffix;

    -- Nếu chưa có dòng nào => tạo mới
    IF NOT FOUND THEN
        INSERT INTO EmpCounter (branchID, roleID, lastNumber)
        VALUES (NEW.branchID, NEW.roleID, 0)
        RETURNING lastNumber INTO next_suffix;
    END IF;

    -- Sinh employeeID = ab c def (6 chữ số); def = next_suffix
    NEW.employeeID := NEW.branchID * 10000 + NEW.roleID * 1000 + next_suffix;

    RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."gen_employee_id_v2"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."generate_employee_id"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
  declare
    max_id int;
  begin
    select coalesce(max(e.employeeID), 10299) into max_id --bắt đầu từ 10300 là nhân viên giao dịch 
    from Employee e
    where roleID = 3;
    new.employeeID := max_id + 1;
    return new;
  end;
  $$;


