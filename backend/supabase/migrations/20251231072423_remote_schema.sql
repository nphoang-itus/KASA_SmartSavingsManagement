CREATE OR REPLACE FUNCTION "public"."maturity_date_setting"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
declare
  term_months int;
begin
    if new.maturitydate IS NOT NULL then
      -- Ngược lại, lấy termPeriod từ bảng TypeSaving
      select termPeriod into term_months
      from TypeSaving
      where typeID = new.typeID;
  -- Gán giá trị maturityDate = registerTime + termPeriod tháng
      new.maturityDate := new.registerTime + (term_months || ' month')::interval;
    END IF ;
  return new;
end;
$$;


